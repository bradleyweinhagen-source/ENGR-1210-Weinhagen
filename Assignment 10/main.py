try:
    import hal_pico as hw
except ImportError:
    import hal_pc as hw

import morse_code
from morse_code import WORD_GAP_MS, DOT_MS, DASH_MS, SYMBOL_GAP_MS, LETTER_GAP_MS, encode_message

# =============================================================================
# WEEK9 Lab - you sent a word
# WEEK10 Lab - extend to send a whole message
# =============================================================================
def send_message(message):
    patterns = encode_message(message)

    for pattern in patterns:
        if pattern == ' ':
            hw.set_led_timed(False, WORD_GAP_MS - LETTER_GAP_MS)# this makes the word gap
        elif pattern == '?':
            print('?')
        else:
            for symbol in pattern:
                if symbol == '.':
                    hw.set_led_timed(True, DOT_MS)
                    hw.set_led_timed(False, SYMBOL_GAP_MS)
                elif symbol == '-':
                    hw.set_led_timed(True, DASH_MS)
                    hw.set_led_timed(False, SYMBOL_GAP_MS)

            hw.set_led_timed(False, LETTER_GAP_MS - SYMBOL_GAP_MS) # This makes the letter gap

