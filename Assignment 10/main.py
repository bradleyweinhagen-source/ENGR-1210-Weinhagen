# Def recive(): Code was generated by Chat GPT Based off my prompt.
def receive():
    pattern = ""
    decoded = ""

    on_reads = 0
    off_reads = 0
    light_was_on = False

    while True:
        value = hw.read_u16()
        light_on = value > 500

        if light_on:
            if light_was_on == False:
                off_time = off_reads * morse_code.SAMPLE_MS

                if off_time >= morse_code.DOT_MS * 5:
                    if pattern != "":
                        decoded = decoded + morse_code.decode_pattern(pattern)
                        pattern = ""

                    decoded = decoded + " "

                elif off_time >= morse_code.DOT_MS * 2:
                    if pattern != "":
                        decoded = decoded + morse_code.decode_pattern(pattern)
                        pattern = ""

                off_reads = 0

            on_reads = on_reads + 1

        else:
            if light_was_on == True:
                on_time = on_reads * morse_code.SAMPLE_MS

                if on_time < morse_code.DOT_MS * 2:
                    pattern = pattern + "."
                else:
                    pattern = pattern + "-"

                on_reads = 0

            off_reads = off_reads + 1

            if off_reads * morse_code.SAMPLE_MS >= morse_code.WORD_GAP_MS * 2:
                break

        light_was_on = light_on
        hw.sleep_ms(morse_code.SAMPLE_MS)

    if pattern != "":
        decoded = decoded + morse_code.decode_pattern(pattern)

    return decoded.strip()
